import { cpSync, existsSync, rmSync, symlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [appArg, pluginArg, homeArg] = process.argv.slice(2);
if (!appArg || !pluginArg || !homeArg) throw new Error('Usage: assemble.mjs APP PURGE_PACKAGE TEMP_HOME');
const app = resolve(appArg), plugin = resolve(pluginArg), home = resolve(homeArg);
const resources = join(app, 'Contents/Resources');
const asar = join(resources, 'app.asar');
const unpackedApp = join(resources, 'app');
const extract = await import(pathToFileURL(join(plugin, 'lib/extract-asar.js')));
extract.extractAsar(asar, unpackedApp);
extract.overlayAsarUnpacked(asar, unpackedApp);
if (!extract.renameAsarAside(asar).renamed) throw new Error('Could not move original app archive');
symlinkSync('../runtime', join(unpackedApp, 'runtime'));
process.env.DSH_HOME = home;
process.env.DSH_SURFACE = 'desktop';
process.env.DSH_DESKTOP_INSTALL = app;
process.env.DSH_BASE = join(unpackedApp, 'dsh/node_modules/@deepseek-ai');
const core = await import(pathToFileURL(join(plugin, 'lib/core.js')));
await core.installOverride(home, false);
const results = await core.applyPatches(process.env.DSH_BASE, undefined, { surface: 'desktop' });
const bad = results.filter(x => ['failed', 'read_error', 'pattern_not_found'].includes(x.status));
if (bad.length) throw new Error(`Purge patch failure: ${JSON.stringify(bad.map(x => ({ id: x.patch_id, status: x.status })))}`);
const counts = {};
for (const result of results) counts[result.status] = (counts[result.status] || 0) + 1;
console.log('Purge patch status:', JSON.stringify(counts));
const template = join(resources, 'profile-template');
cpSync(join(home, 'profiles'), join(template, 'profiles'), { recursive: true, verbatimSymlinks: true });
cpSync(join(home, 'prompt-inject.md'), join(template, 'prompt-inject.md'));
if (existsSync(join(resources, 'app-update.yml'))) rmSync(join(resources, 'app-update.yml'));
